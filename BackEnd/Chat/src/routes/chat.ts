import { Router } from "express";
import { createNewChat, getAllChats, getMessagesByChat, sendMessage } from "../controllers/chat.js";
import { isAuth } from "../middlewares/isAuth.js";
import { upload } from "../middlewares/multer.js";
const router = Router();
router.use(isAuth);
router.post("/new", createNewChat);
router.get("/all", getAllChats);
router.post("/message", upload.single("image"), sendMessage);
router.get("/message/:chatId", getMessagesByChat);
export default router;
